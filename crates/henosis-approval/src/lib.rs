    /// Concurrent callers receive authorization consumption at most once.
    #[test]
    fn concurrent_consume_is_at_most_once() {
        let store = Arc::new(ApprovalStore::open_in_memory().expect("open"));
        let tenant = TenantId::new();
        let principal = PrincipalId::new();
        let approval = store
            .create_or_get_pending(request(tenant, principal, [5; 32]), 101)
            .expect("create");
        store
            .decide(
                tenant,
                approval.id,
                ApprovalDecision::Approve,
                "operator",
                None,
                110,
            )
            .expect("decide");
        let token_identity = approval.token_identity.clone();
        let mut handles = Vec::new();
        for _ in 0..8 {
            let store = Arc::clone(&store);
            let token_identity = token_identity.clone();
            handles.push(std::thread::spawn(move || {
                store
                    .consume_approved(
                        tenant,
                        approval.id,
                        principal,
                        &token_identity,
                        &[5; 32],
                        "v9",
                        120,
                    )
                    .expect("consume")
                    .is_some()
            }));
        }
        assert_eq!(
            handles
                .into_iter()
                .filter_map(|handle| handle.join().ok())
                .filter(|used| *used)
                .count(),
            1
        );
    }

