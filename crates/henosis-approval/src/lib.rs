    /// An expired lifecycle permits one fresh pending approval for the same exact request.
    #[test]
    fn expired_request_can_start_one_fresh_approval_lifecycle() {
        let store = ApprovalStore::open_in_memory().expect("open");
        let tenant = TenantId::new();
        let principal = PrincipalId::new();
        let first_request = request(tenant, principal, [12; 32]);
        let first = store
            .create_or_get_pending(first_request.clone(), 101)
            .expect("create first approval");
        store
            .decide(
                tenant,
                first.id,
                ApprovalDecision::Approve,
                "operator",
                None,
                110,
            )
            .expect("approve first lifecycle");
        assert_eq!(
            store.expire(tenant, 200).expect("expire first lifecycle"),
            1
        );

        let mut renewed_request = first_request;
        renewed_request.created_at = 201;
        renewed_request.expires_at = 301;
        let renewed = store
            .create_or_get_pending(renewed_request.clone(), 201)
            .expect("create renewed approval");
        let duplicate = store
            .create_or_get_pending(renewed_request, 201)
            .expect("reuse active renewed approval");

        assert_ne!(renewed.id, first.id);
        assert_eq!(renewed.status, ApprovalStatus::Pending);
        assert_eq!(duplicate.id, renewed.id);
    }

